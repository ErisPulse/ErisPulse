#!/usr/bin/env python
"""
文档包自动构建器（把 docs/{lang} 打成单个分发 zip）

与 ai_prompts 并存（提示词面向"整段注入"工作流，本脚本产出
文档原文包——不合并、不改写，保持 docs/{lang} 的目录结构与文件原貌，
AI 按需挑文档加载，避免合并稿带来的上下文浪费与结构丢失）。

产物：docs/{lang}/ai-support/skills.zip（每语言一个）。
内容：该语言全部文档原文 + 一份 README.md 总索引——按目录分组，
逐篇标注「什么时候需要读这篇」触发描述，AI 据此挑选要读的文档。

属构建产物，**由 CI 生成后提交回开发分支**（官网直接链接分支文件下载）。

用法::

    python -m scripts.tools gen skills                     # 全语言生成
    python -m scripts.tools gen skills --lang zh-CN        # 单语言
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from ..common import REPO_ROOT

DOCS_ROOT = REPO_ROOT / "docs"

# 不入包的内容：索引产物、AI 物料（prompts 与本包并列自分发）、翻译流程内部文档
_EXCLUDE_FILES = {"translate-workflow.md"}
_EXCLUDE_DIRS = {"_meta", "ai-support"}

_TRIGGER_MARKERS = (
    "什么时候需要读这篇",
    "When to read this",
    "いつこのドキュメントを読むべきか",
    "Когда читать этот документ",
    "什麼時候需要讀這篇",
)

_PACK_TEXT = {
    "zh": {
        "title": "# ErisPulse 文档包（{lang}）",
        "intro": (
            "本压缩包由 CI 从 `docs/{lang}/` 自动打包：收录全部文档原文"
            "（不合并、不改写），另附本 README 作为总索引。"
        ),
        "usage": (
            "## 使用\n\n"
            "1. 解压后把整个目录放进工作区（IDE / 智能体均可），或按需把单个文档投喂给 AI\n"
            "2. 按下面的索引挑文档：先看「什么时候读」，只加载需要的那几篇，不必全文灌入\n"
        ),
        "root_group": "根目录文档",
        "table_head": "| 文档 | 什么时候读 |\n|---|---|",
        "note": "> 由 `python -m scripts.tools gen skills` 生成，请勿手改。",
    },
    "en": {
        "title": "# ErisPulse Docs Pack ({lang})",
        "intro": (
            "Auto-packed by CI from `docs/{lang}/`: all documents as-is "
            "(no merging, no rewriting), plus this README as the index."
        ),
        "usage": (
            "## Usage\n\n"
            "1. Unzip and put the folder into your workspace (IDE / agent), or feed individual documents to the AI as needed\n"
            "2. Pick documents via the index below: check \"when to read\" and load only what you need\n"
        ),
        "root_group": "Root documents",
        "table_head": "| Document | When to read |\n|---|---|",
        "note": "> Generated by `python -m scripts.tools gen skills`; do not edit by hand.",
    },
}


def _extract_brief(text: str) -> str:
    """提取每篇的索引简介：优先「什么时候需要读这篇」触发描述，回退首段非标题文本"""
    for marker in _TRIGGER_MARKERS:
        m = re.search(re.escape(marker) + r"[^：:]*[：:]\s*([^\n]+)", text)
        if m:
            brief = m.group(1).strip()
            for tail in ("不需要则跳过，不影响其它功能的使用。", "不需要则跳过。"):
                brief = brief.replace(tail, "")
            return brief.strip().rstrip("。；;") + "。"
    m = re.search(r"> \[!TIP\][^\n]*\n>\s*([^\n]+)", text)
    if m:
        return m.group(1).strip()
    for line in text.splitlines():
        s = line.strip()
        if s and not s.startswith(("#", ">", "!", "[", "-")) and not s.startswith("---"):
            return s
    return ""


def _doc_title(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def collect_docs(docs_lang_dir: Path) -> list[Path]:
    """该语言全部待打包文档（相对 docs_lang_dir 的路径），已排除索引/物料/内部文档"""
    rels: list[Path] = []
    for path in sorted(docs_lang_dir.rglob("*.md")):
        rel = path.relative_to(docs_lang_dir)
        parts = rel.parts
        if parts[0] in _EXCLUDE_DIRS:
            continue
        if len(parts) == 1 and parts[0] in _EXCLUDE_FILES:
            continue
        rels.append(rel)
    return rels


def write_index(lang: str, docs_lang_dir: Path, rels: list[Path], out_file: Path) -> None:
    """生成总索引 README：按目录分组，逐篇给触发描述"""
    text = _PACK_TEXT["zh"] if lang.startswith("zh") else _PACK_TEXT["en"]
    lines = [text["title"].format(lang=lang), "", text["intro"].format(lang=lang), "", text["usage"]]

    groups: dict[str, list[Path]] = {}
    for rel in rels:
        groups.setdefault(rel.parts[0] if len(rel.parts) > 1 else "", []).append(rel)

    lines.append("## 索引\n" if lang.startswith("zh") else "## Index\n")
    for group in sorted(groups):
        if group:
            lines.append(f"### {group}/\n")
        else:
            lines.append(f"### {text['root_group']}\n")
        lines.append(text["table_head"])
        for rel in sorted(groups[group]):
            raw = (docs_lang_dir / rel).read_text(encoding="utf-8", errors="replace")
            brief = _extract_brief(raw) or _doc_title(raw)
            lines.append(f"| `{rel.as_posix()}` | {brief} |")
        lines.append("")
    lines.append(text["note"])
    out_file.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def write_zip(docs_lang_dir: Path, rels: list[Path], index_file: Path) -> Path:
    """把文档原文 + 索引打成分发 zip（与物料文档并列的下载物）"""
    import zipfile

    zip_path = docs_lang_dir / "ai-support" / "skills.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(index_file, arcname="README.md")
        for rel in rels:
            zf.write(docs_lang_dir / rel, arcname="docs/" + rel.as_posix())
    return zip_path


def available_langs() -> list[str]:
    return sorted(
        d.name for d in DOCS_ROOT.iterdir() if d.is_dir() and d.name != "_meta"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="文档包构建器：docs/{lang} → skills.zip")
    parser.add_argument("--lang", default=None, help="仅生成单语言（默认全语言）")
    args = parser.parse_args(argv)

    langs = [args.lang] if args.lang else available_langs()
    no_brief: list[str] = []

    for lang in langs:
        docs_lang_dir = DOCS_ROOT / lang
        if not docs_lang_dir.exists():
            print(f"  [skip] docs/{lang} 不存在", file=sys.stderr)
            continue
        rels = collect_docs(docs_lang_dir)
        index_file = docs_lang_dir / "ai-support" / "README.index.tmp"
        write_index(lang, docs_lang_dir, rels, index_file)
        for rel in rels:
            raw = (docs_lang_dir / rel).read_text(encoding="utf-8", errors="replace")
            if not _extract_brief(raw):
                no_brief.append(f"{lang}/{rel.as_posix()}")
        zip_path = write_zip(docs_lang_dir, rels, index_file)
        index_file.unlink()
        print(f"  [built] {zip_path.relative_to(REPO_ROOT).as_posix()} ({len(rels)} 篇文档)")

    if no_brief:
        print(
            "\n[warn] 以下文档缺少「什么时候需要读这篇」触发描述，索引简介使用了标题兜底"
            "（请补齐后重新生成）：",
            file=sys.stderr,
        )
        for m in no_brief:
            print(f"  - {m}", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main())
